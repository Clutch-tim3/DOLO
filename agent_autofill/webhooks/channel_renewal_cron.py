"""
Keeping Google Drive push channels alive.

=============================================================================
THE NUMBER THAT MATTERS: 86,400
=============================================================================
A Drive `files.watch` channel lives for at most **86,400 seconds (1 day)**, and
for **3,600 seconds (1 hour)** if you do not ask for more. It is not ~7 days.
That figure is what the original spec assumed, and building on it produces a
renewal schedule that silently lets every channel die -- the webhook simply
stops arriving, no error is raised anywhere, and the first symptom is a user
asking why their tender folder stopped syncing a fortnight ago.

There is also no way to extend a channel in place. "Renewal" is: create a
replacement, confirm it, then `channels.stop` the old one. In that order.

=============================================================================
WHY A DAILY CRON IS BROKEN BY CONSTRUCTION
=============================================================================
Take TTL = 86,400s, a cron period P, and a predicate "renew if the channel
expires within `threshold` seconds".

A channel is eligible for renewal during the window

    [expiry - min(threshold, TTL),  expiry)

whose length is L = min(threshold, TTL). Cron ticks are spaced P apart, and
the channel's creation time has arbitrary phase relative to them -- nothing
aligns a scheduler to the moment a user connected their Drive. In the worst
phase, a half-open window of length L contains exactly

    floor(L / P)

ticks. That is the number of chances the system is *guaranteed* to get. And
the first eligible tick lands anywhere in [expiry - L, expiry - L + P), so the
overlap between the replacement and the old channel is guaranteed to exceed

    L - P

and nothing more.

Now substitute a daily cron, P = 86,400, with the only threshold that makes
sense at that cadence, 24h:

    L                    = min(86,400, 86,400) = 86,400
    guaranteed attempts  = floor(86,400 / 86,400) = 1
    survivable failures  = 1 - 1 = 0
    guaranteed overlap   = 86,400 - 86,400 = 0

One attempt. Zero tolerance. If that single run is late, throttled, hits a
cold start, hits a 5xx from Drive, or lands in a deploy window, the channel is
dead and the next opportunity is 24 hours after it already expired. And the
overlap is zero, so even the successful case hands over at the exact instant
of expiry with no margin for clock skew between our scheduler and Google's
expiry clock.

There is a second, subtler failure. With threshold >= TTL the predicate
"expires within 24 hours" is **true for every channel from the moment it is
created**. It carries no information: it does not select the channels that
need attention, it selects all of them, every run. A filter that always
returns everything is not a filter, and it hides the case it was meant to
catch.

Six hours with a twelve-hour threshold:

    L                    = min(43,200, 86,400) = 43,200
    guaranteed attempts  = floor(43,200 / 21,600) = 2
    survivable failures  = 1
    guaranteed overlap   > 43,200 - 21,600 = 21,600s (6 hours)
    threshold < TTL      -> the predicate actually discriminates

Two independent chances inside every channel's lifetime, at least six hours of
deliberate overlap on the handover, and a predicate that means something.

    cadence         attempts   survivable failures   guaranteed overlap
    ------------------------------------------------------------------
    24h / 24h thr.     1              0                    0s
    12h / 12h thr.     1              0                    0s
    12h / 24h thr.     2              1                43,200s  (degenerate predicate)
     6h / 12h thr.     2              1                21,600s  <- chosen
     6h /  6h thr.     1              0                    0s

The threshold has to be at least twice the interval, and strictly less than
the TTL. `assert_cadence_is_sound()` enforces exactly that at import.

=============================================================================
SCHEDULING
=============================================================================
    gcloud scheduler jobs create http autofill-channel-renewal \\
        --project cairoai \\
        --schedule "0 */6 * * *" \\
        --uri "https://<region>-cairoai.cloudfunctions.net/api/api/autofill/webhooks/renew" \\
        --http-method POST \\
        --oidc-service-account-email <sa>@cairoai.iam.gserviceaccount.com

The endpoint MUST be authenticated (OIDC above, or a shared secret). An open
renewal endpoint lets anyone burn Drive quota and churn every channel.

Note the CLAUDE.md trap: if this becomes a function in `main.py`, it also has
to appear in `functions.yaml`, which is generated by
`scripts/gen_functions_yaml.py` -- the CLI reads that file instead of running
discovery and silently drops anything missing from it.

=============================================================================
UNVERIFIED
=============================================================================
The arithmetic in this module is tested and the simulation below is exercised
across every creation phase. What has NOT happened: a real channel created
against a real Drive account and observed to survive past its original
expiry. That needs a live OAuth connection. See `providers/VERIFICATION.md`.
"""

