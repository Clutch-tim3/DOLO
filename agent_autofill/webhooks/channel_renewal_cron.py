# Google's limits. Not ours to choose.
DRIVE_CHANNEL_MAX_TTL_SECONDS = 86_400
DRIVE_CHANNEL_DEFAULT_TTL_SECONDS = 3_600

# Ours. See the table above.
RENEWAL_INTERVAL_SECONDS = 6 * 3_600    # 21,600
RENEWAL_THRESHOLD_SECONDS = 12 * 3_600  # 43,200

MIN_GUARANTEED_ATTEMPTS = 2

CRON_SCHEDULE = "0 */6 * * *"


# =============================================================================
# The arithmetic
# =============================================================================


def eligible_window_seconds(ttl: float, threshold: float) -> float:
    """
    Length of the interval during which a channel qualifies for renewal.

    Capped at the TTL because a channel cannot be eligible before it exists --
    this is what makes a threshold larger than the TTL contribute nothing.
    """
    return min(float(threshold), float(ttl))


def guaranteed_attempts(ttl: float, interval: float, threshold: float) -> int:
    """
    Renewal attempts guaranteed inside the eligible window, worst-case phase.

    `floor(L / P)`: ticks are spaced `interval` apart with arbitrary phase, so
    a half-open window of length L contains at least floor(L / P) of them.
    Rounding up here would be assuming the scheduler happens to be aligned
    with the moment a user connected their Drive.
    """
    if interval <= 0:
        raise ValueError("interval must be positive")
    return int(math.floor(eligible_window_seconds(ttl, threshold) / float(interval)))


def guaranteed_overlap_seconds(ttl: float, interval: float, threshold: float) -> float:
    """
    Lower bound on how long the replacement and the old channel coexist.

    Strictly, the overlap is > L - P; this returns L - P (clamped at zero) as
    the safe floor. Overlap is not waste: it is the margin that absorbs clock
    skew between our scheduler and Google's expiry, and it means no change can
    fall into a gap between two channels.
    """
    return max(0.0, eligible_window_seconds(ttl, threshold) - float(interval))


def survivable_consecutive_failures(ttl: float, interval: float, threshold: float) -> int:
    """How many runs in a row may fail before the channel is lost."""
    return max(0, guaranteed_attempts(ttl, interval, threshold) - 1)


def threshold_is_degenerate(ttl: float, threshold: float) -> bool:
    """
    True when "expiring within `threshold`" is true for every live channel.

    At that point the predicate selects everything from the moment of
    creation, which is not a filter and disguises the channels that are
    genuinely close to expiry.
    """
    return float(threshold) >= float(ttl)


def assess_cadence(
    ttl: float = DRIVE_CHANNEL_MAX_TTL_SECONDS,
    interval: float = RENEWAL_INTERVAL_SECONDS,
    threshold: float = RENEWAL_THRESHOLD_SECONDS,
    min_attempts: int = MIN_GUARANTEED_ATTEMPTS,
) -> dict[str, Any]:
    """Full verdict on a proposed schedule. Pure arithmetic, no I/O."""
    attempts = guaranteed_attempts(ttl, interval, threshold)
    overlap = guaranteed_overlap_seconds(ttl, interval, threshold)
    degenerate = threshold_is_degenerate(ttl, threshold)
    sufficient = attempts >= min_attempts and overlap > 0 and not degenerate

    reasons: list[str] = []
    if attempts < min_attempts:
        reasons.append(
            f"only {attempts} guaranteed renewal attempt(s) per channel lifetime; "
            f"{min_attempts} required so a single failed run is survivable"
        )
    if overlap <= 0:
        reasons.append(
            "guaranteed overlap is zero -- the replacement would be created at "
            "the instant of expiry, leaving no margin for scheduler or clock skew"
        )
    if degenerate:
        reasons.append(
            f"threshold ({threshold:.0f}s) >= channel TTL ({ttl:.0f}s), so every "
            "channel qualifies from the moment it is created and the predicate "
            "selects everything"
        )

    return {
        "ttl_seconds": float(ttl),
        "interval_seconds": float(interval),
        "threshold_seconds": float(threshold),
        "eligible_window_seconds": eligible_window_seconds(ttl, threshold),
        "guaranteed_attempts": attempts,
        "survivable_consecutive_failures": survivable_consecutive_failures(
            ttl, interval, threshold
        ),
        "guaranteed_overlap_seconds": overlap,
        "threshold_is_degenerate": degenerate,
        "sufficient": sufficient,
        "reasons": reasons,
    }


def assert_cadence_is_sound(
    ttl: float = DRIVE_CHANNEL_MAX_TTL_SECONDS,
    interval: float = RENEWAL_INTERVAL_SECONDS,
    threshold: float = RENEWAL_THRESHOLD_SECONDS,
) -> dict[str, Any]:
    """Raise if the configured schedule cannot keep a channel alive."""
    verdict = assess_cadence(ttl, interval, threshold)
    if not verdict["sufficient"]:
        raise ValueError(
            "renewal cadence is unsound: " + "; ".join(verdict["reasons"])
        )
    return verdict


# Fails loudly at import if someone edits the constants into a broken schedule.
CADENCE = assert_cadence_is_sound()


# =============================================================================
# Simulation
# =============================================================================


def simulate_renewal(
    created_at: float,
    ttl_seconds: float = DRIVE_CHANNEL_MAX_TTL_SECONDS,
    interval_seconds: float = RENEWAL_INTERVAL_SECONDS,
    threshold_seconds: float = RENEWAL_THRESHOLD_SECONDS,
    cron_epoch: float = 0.0,
    failing_runs: int = 0,
) -> dict[str, Any]:
    """
    Walk a channel's life against a fixed-phase cron and report what happens.

    `cron_epoch` is the wall-clock anchor of the schedule; ticks fall at
    `cron_epoch + k * interval`. `created_at` is deliberately independent of
    it, because a user connects their Drive whenever they like. `failing_runs`
    makes the first N eligible attempts fail, which is how the "survives a
    missed run" property is checked rather than assumed.

    Returns the renewal instant, the overlap it achieved, and whether the
    channel died first.
    """
    expiry = created_at + ttl_seconds
    first_k = math.ceil((created_at - cron_epoch) / interval_seconds)

    ticks: list[float] = []
    eligible: list[float] = []
    renewed_at: float | None = None
    failures_left = int(failing_runs)

    k = first_k
    while True:
        tick = cron_epoch + k * interval_seconds
        if tick >= expiry:
            break
        ticks.append(tick)
        if (expiry - tick) <= threshold_seconds:
            eligible.append(tick)
            if renewed_at is None:
                if failures_left > 0:
                    failures_left -= 1
                else:
                    renewed_at = tick
        k += 1

    return {
        "created_at": created_at,
        "expiry": expiry,
        "ttl_seconds": ttl_seconds,
        "interval_seconds": interval_seconds,
        "threshold_seconds": threshold_seconds,
        "failing_runs": int(failing_runs),
        "ticks_before_expiry": len(ticks),
        "eligible_ticks": len(eligible),
        "first_eligible_at": eligible[0] if eligible else None,
        "renewed_at": renewed_at,
        "renewed_before_expiry": renewed_at is not None,
        "overlap_seconds": (expiry - renewed_at) if renewed_at is not None else 0.0,
    }


# =============================================================================
# The job
# =============================================================================


def run_renewal_cycle(
    provider_factory: Callable[[str], Any] | None = None,
    now: float | None = None,
    threshold_seconds: float = RENEWAL_THRESHOLD_SECONDS,
    providers: Iterable[str] = ("google_drive",),
) -> dict[str, Any]:
    """
    Renew every channel inside the threshold. Safe to run more often than
    scheduled; renewing early only lengthens the overlap.

    One channel's failure never aborts the cycle -- a single company with a
    revoked token would otherwise stop every other company's channel from
    being renewed, which converts one broken connection into an outage.

    Dropbox is not in `providers` by default: its webhook registration lives
    in the App Console and does not expire, so it has nothing to renew. Its
    rows carry `expiration_at = inf` and can never match the query anyway.
    """
    now = time.time() if now is None else now
    if provider_factory is None:
        provider_factory = _default_provider_factory

    report: dict[str, Any] = {
        "ran_at": now,
        "threshold_seconds": threshold_seconds,
        "interval_seconds": RENEWAL_INTERVAL_SECONDS,
        "due": 0,
        "renewed": 0,
        "failed": 0,
        "already_expired": 0,
        "details": [],
    }

    for provider_name in providers:
        due: list[WebhookChannel] = channel_registry.channels_due_for_renewal(
            now=now, threshold_seconds=threshold_seconds, provider=provider_name
        )
        report["due"] += len(due)
        if not due:
            continue

        provider = provider_factory(provider_name)
        for channel in due:
            remaining = channel.seconds_remaining(now)
            entry: dict[str, Any] = {
                "provider": provider_name,
                "channel_id": channel.channel_id,
                "company_id": channel.company_id,
                "seconds_remaining": round(remaining),
            }
            if remaining <= 0:
                report["already_expired"] += 1
                entry["was_expired"] = True

            try:
                new_channel = provider.renew_webhook(channel.channel_id, now=now)
            except Exception as exc:
                report["failed"] += 1
                entry["status"] = "failed"
                entry["error"] = f"{type(exc).__name__}: {exc}"
                logger.error(
                    "channel renewal failed provider=%s channel_id=%s company_id=%s",
                    provider_name,
                    channel.channel_id,
                    channel.company_id,
                    exc_info=True,
                )
            else:
                report["renewed"] += 1
                entry["status"] = "renewed"
                entry["new_channel_id"] = new_channel.channel_id
                entry["new_expiration_at"] = new_channel.expiration_at
                entry["overlap_seconds"] = round(
                    max(0.0, channel.expiration_at - now)
                )
            report["details"].append(entry)

    logger.info(
        "channel renewal cycle complete due=%s renewed=%s failed=%s already_expired=%s",
        report["due"],
        report["renewed"],
        report["failed"],
        report["already_expired"],
    )
    return report


def _default_provider_factory(name: str) -> Any:
    if name == "google_drive":
        from agent_autofill.providers.google_drive_provider import GoogleDriveProvider

        return GoogleDriveProvider()
    if name == "dropbox":
        from agent_autofill.providers.dropbox_provider import DropboxProvider

        return DropboxProvider()
    raise ValueError(f"unknown provider: {name!r}")


def main() -> int:  # pragma: no cover - operational entry point
    """CLI entry point, for a Cloud Scheduler job that shells out."""
    import json

    result = run_renewal_cycle()
    print(json.dumps(result, indent=2, default=str))
    return 1 if result["failed"] else 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
